import streamlit as st
import pandas as pd
import joblib
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    matthews_corrcoef,
    confusion_matrix,
    classification_report
)

# ======================================================
# PAGE CONFIG
# ======================================================

st.set_page_config(
    page_title="Breast Cancer Classification",
    page_icon="🩺",
    layout="wide"
)

st.title("🩺 Breast Cancer Classification System")
st.write(
    "Upload a test dataset and evaluate any of the trained machine learning models."
)

# ======================================================
# MODEL FILES
# ======================================================

MODEL_FILES = {
    "Logistic Regression": "model/logistic_regression.pkl",
    "Decision Tree": "model/decision_tree.pkl",
    "KNN": "model/knn.pkl",
    "Naive Bayes": "model/naive_bayes.pkl",
    "Support Vector Machine": "model/support_vector_machine.pkl"
}

# Models requiring scaling
SCALED_MODELS = [
    "Logistic Regression",
    "KNN",
    "Support Vector Machine"
]

# ======================================================
# MODEL SELECTION
# ======================================================

selected_model = st.selectbox(
    "Select Model",
    list(MODEL_FILES.keys())
)

# ======================================================
# FILE UPLOAD
# ======================================================

uploaded_file = st.file_uploader(
    "Upload Test CSV File",
    type=["csv"]
)

# ======================================================
# PROCESS DATA
# ======================================================

if uploaded_file is not None:

    try:

        df = pd.read_csv(uploaded_file)

        st.subheader("Uploaded Dataset")
        st.dataframe(df.head())

        # ----------------------------------------------
        # Check target column
        # ----------------------------------------------

        if "target" not in df.columns:
            st.error(
                "The uploaded CSV must contain a 'target' column."
            )
            st.stop()

        X = df.drop("target", axis=1)
        y = df["target"]

        # ----------------------------------------------
        # Load model
        # ----------------------------------------------

        model = joblib.load(
            MODEL_FILES[selected_model]
        )

        # ----------------------------------------------
        # Scale if required
        # ----------------------------------------------

        if selected_model in SCALED_MODELS:

            scaler = joblib.load(
                "model/scaler.pkl"
            )

            X_input = scaler.transform(X)

        else:
            X_input = X

        # ----------------------------------------------
        # Predictions
        # ----------------------------------------------

        y_pred = model.predict(X_input)

        if hasattr(model, "predict_proba"):
            y_prob = model.predict_proba(X_input)[:, 1]
        else:
            y_prob = y_pred

        # ----------------------------------------------
        # Metrics
        # ----------------------------------------------

        accuracy = accuracy_score(y, y_pred)

        precision = precision_score(
            y,
            y_pred
        )

        recall = recall_score(
            y,
            y_pred
        )

        f1 = f1_score(
            y,
            y_pred
        )

        auc = roc_auc_score(
            y,
            y_prob
        )

        mcc = matthews_corrcoef(
            y,
            y_pred
        )

        # ----------------------------------------------
        # Display Metrics
        # ----------------------------------------------

        st.subheader("📊 Evaluation Metrics")

        col1, col2, col3 = st.columns(3)

        col1.metric(
            "Accuracy",
            f"{accuracy:.4f}"
        )

        col2.metric(
            "AUC",
            f"{auc:.4f}"
        )

        col3.metric(
            "Precision",
            f"{precision:.4f}"
        )

        col1, col2, col3 = st.columns(3)

        col1.metric(
            "Recall",
            f"{recall:.4f}"
        )

        col2.metric(
            "F1 Score",
            f"{f1:.4f}"
        )

        col3.metric(
            "MCC",
            f"{mcc:.4f}"
        )

        # ----------------------------------------------
        # Confusion Matrix
        # ----------------------------------------------

        st.subheader("📈 Confusion Matrix")

        cm = confusion_matrix(
            y,
            y_pred
        )

        fig, ax = plt.subplots(figsize=(5, 4))

        sns.heatmap(
            cm,
            annot=True,
            fmt="d",
            cmap="Blues",
            ax=ax
        )

        ax.set_xlabel("Predicted")
        ax.set_ylabel("Actual")
        ax.set_title(f"{selected_model} Confusion Matrix")

        st.pyplot(fig)

        # ----------------------------------------------
        # Classification Report
        # ----------------------------------------------

        st.subheader("📋 Classification Report")

        report = classification_report(
            y,
            y_pred
        )

        st.text(report)

        # ----------------------------------------------
        # Download Predictions
        # ----------------------------------------------

        result_df = df.copy()
        result_df["prediction"] = y_pred

        csv = result_df.to_csv(
            index=False
        ).encode("utf-8")

        st.download_button(
            label="⬇ Download Predictions",
            data=csv,
            file_name="predictions.csv",
            mime="text/csv"
        )

    except Exception as e:

        st.error(f"Error: {e}")

